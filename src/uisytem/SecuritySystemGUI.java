    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String House_Mode = HOUSE_MODE.getSelectedItem().toString();
        String Motion_Detected = MOTION_DE.getSelectedItem().toString();

        boolean motion_detected;

        if (Motion_Detected.equalsIgnoreCase("yes")) {
            motion_detected = true;
        } else {
            motion_detected = false;
        }

        SecuritySystem c1 = new SecuritySystem(House_Mode, motion_detected);

        c1.evaluate();

        String Action = c1.printACT();
        String explain = c1.printEXP();

        TEXTA.setText("Action is: " + Action + "\n" + "Explanation is: " + explain);

        clear_input();

                try {
            Connection con = DBConnection.getConnection();
            PreparedStatement stmt = con.prepareStatement("INSERT INTO history(user_id, system_name, action, exp, operation_date) VALUES (?, ?, ?, ?, SYSDATE)");

            stmt.setInt(1, user_id);
            stmt.setString(2, "Security System Control");
            stmt.setString(3, Action);
            stmt.setString(4, explain);

            int rows = stmt.executeUpdate();

            if (rows > 0) {
                JOptionPane.showMessageDialog(this, "DONE - Action saved successfully");
            }
        } catch (SQLException ex) {
            Logger.getLogger(ClimateSystemUI.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

