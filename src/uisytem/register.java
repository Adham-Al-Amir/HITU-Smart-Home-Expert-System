    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {

            String User_Name = USER_NAME.getText().trim();
            String pass_text = Password.getText().trim();
            String confirm_text = Confirm.getText().trim();

            if (User_Name.isEmpty() || pass_text.isEmpty() || confirm_text.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please fill all fields");
                return;
            } else if (!pass_text.equals(confirm_text)) {
                JOptionPane.showMessageDialog(this, "Passwords do not match");
                return;
            } else {

                Connection con = DBConnection.getConnection();
                PreparedStatement stmt = con.prepareStatement("INSERT INTO home_user(username,user_password) VALUES (?,?)");

                stmt.setString(1, User_Name);
                stmt.setString(2, pass_text);

                stmt.executeUpdate();
                JOptionPane.showMessageDialog(this, "Account Created Successfully!");
                clear_input();
            }
        } catch (SQLException ex) {
            Logger.getLogger(register.class.getName()).log(Level.SEVERE, null, ex);
        }

    }//GEN-LAST:event_jButton1ActionPerformed

