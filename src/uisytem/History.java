    public void Show_Data_table_History_Page() {

        try {

            Connection con = DBConnection.getConnection();
            PreparedStatement stmt = con.prepareStatement("SELECT system_name, action,exp, TO_CHAR(operation_date, 'DD-Mon-YYYY') AS operation_date FROM history WHERE user_id = ?");
            stmt.setInt(1, user_id);
            ResultSet rs = stmt.executeQuery();

            DefaultTableModel model_ = (DefaultTableModel) Table_1.getModel();
            model_.setRowCount(0); // تفريغ الجدول قبل التحديث

            while (rs.next()) {
                Object[] obj = {
                    rs.getString("system_name"),
                    rs.getString("action"),
                    rs.getString("exp"),
                    rs.getString("operation_date"),};
                model_.addRow(obj);
            }
        } catch (SQLException ex) {
            Logger.getLogger(History.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

