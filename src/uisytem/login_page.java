    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String User_Name = USER_NAME.getText();
        String pass = Pass.getText();

        if (User_Name.isEmpty() || pass.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill all fields");
            return;
        } else {
            try {
                Connection con = DBConnection.getConnection();
                PreparedStatement stmt = con.prepareStatement("SELECT user_id ,username, user_password FROM home_user WHERE username =? and user_password =?");
                stmt.setString(1, User_Name);
                stmt.setString(2, pass);

                ResultSet rs = stmt.executeQuery();

                if (rs.next()) {
                    JOptionPane.showMessageDialog(this, "Login Successfully! Welcome " + rs.getString("username"));

                    clear_input();

                    int user_id = rs.getInt("user_id");
                    
                    SmartHomeGUI h1 = new SmartHomeGUI(user_id);
                    h1.show();
                    dispose();

                } else {
                    JOptionPane.showMessageDialog(this, "Invalid User Name or Password!");
                }
            } catch (SQLException ex) {
                Logger.getLogger(login_page.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

